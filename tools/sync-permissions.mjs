import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const backend = new URL('../../coffee_shop_be/src/common/consts/', import.meta.url)
function objectFrom(file, name) {
  const path = fileURLToPath(new URL(file, backend))
  const source = ts.createSourceFile(path, readFileSync(path, 'utf8'), ts.ScriptTarget.Latest, true)
  let result
  function visit(node) {
    if (ts.isVariableDeclaration(node) && node.name.getText(source) === name) {
      let value = node.initializer
      while (value && (ts.isAsExpression(value) || ts.isSatisfiesExpression(value))) value = value.expression
      if (!value || !ts.isObjectLiteralExpression(value)) throw new Error(`Expected object ${name}`)
      result = Object.fromEntries(value.properties.map((property) => {
        if (!ts.isPropertyAssignment(property)) throw new Error(`Invalid ${name} member`)
        const value = property.initializer
        const values = ts.isArrayLiteralExpression(value) ? [...value.elements] : [value]
        if (!values.every(ts.isStringLiteral)) throw new Error(`Expected strings in ${name}`)
        return [property.name.getText(source), values.length === 1 ? values[0].text : values.map((entry) => entry.text)]
      }))
    }
    ts.forEachChild(node, visit)
  }
  visit(source)
  if (!result) throw new Error(`Missing ${name}`)
  return result
}

const keys = objectFrom('permission-keys.ts', 'PermissionKeys')
const labels = objectFrom('permission-labels.ts', 'PermissionLabels')
if (new Set(Object.values(keys)).size !== Object.keys(keys).length) throw new Error('Duplicate permission keys')
if (Object.keys(keys).length !== Object.keys(labels).length) throw new Error('Permission labels are incomplete')
const byKey = Object.fromEntries(Object.entries(keys).map(([name, key]) => {
  if (!Array.isArray(labels[name]) || labels[name].length !== 2) throw new Error(`Missing labels for ${name}`)
  return [key, labels[name]]
}))
const output = '// Generated by pnpm permissions:sync. Do not edit manually.\n' +
  `export const PermissionKeys = ${JSON.stringify(keys, null, 2)} as const\n\n` +
  'export type PermissionKey = (typeof PermissionKeys)[keyof typeof PermissionKeys]\n\n' +
  `export const PermissionLabels = ${JSON.stringify(byKey, null, 2)} as const satisfies Record<PermissionKey, readonly [string, string]>\n`
const path = new URL('../src/shared/auth/permission-contract.ts', import.meta.url)
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== output) {
    throw new Error('Permission contract differs from backend. Run pnpm permissions:sync and commit the result.')
  }
  console.log(`Permission contract matches backend (${Object.keys(keys).length} permissions).`)
} else {
  writeFileSync(path, output)
  console.log(`Updated ${Object.keys(keys).length} permission keys and labels.`)
}
